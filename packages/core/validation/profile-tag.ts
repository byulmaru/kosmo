const fullCaseFold = (value: string): string =>
  Array.from(value, (character) => {
    const codePoint = character.codePointAt(0)!;
    return fullCaseFoldOverrides[codePoint] ?? character.toLowerCase();
  }).join('');

const profileTagNamePattern = /^[\p{Letter}\p{Number}_]+$/u;

export const normalizeProfileTagName = (value: string): string =>
  fullCaseFold(value.trim().replace(/^#/, '').normalize('NFKC'));

export const profileTagNameSchema = z.string().transform((value, context) => {
  const normalized = normalizeProfileTagName(value);

  if (
    normalized.length === 0 ||
    [...normalized].length > 20 ||
    !profileTagNamePattern.test(normalized)
  ) {
    context.addIssue({
      code: 'custom',
      message: 'Profile Tag는 1~20자의 문자, 숫자 또는 밑줄만 사용할 수 있어요.',
    });
    return z.NEVER;
  }

  return normalized;
});

export const profileTagsSchema = z
  .array(profileTagNameSchema)
  .max(5, 'Profile Tag는 최대 5개까지 추가할 수 있어요.')
  .superRefine((tags, context) => {
    tags.forEach((tag, index) => {
      if (tags.indexOf(tag) !== index) {
        context.addIssue({
          code: 'custom',
          path: [index],
          message: '정규화한 Profile Tag는 중복될 수 없어요.',
        });
      }
    });
  });

export const profileTagsInputSchema = profileTagsSchema.nullable().optional();
